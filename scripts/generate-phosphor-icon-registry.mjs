import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = path.join(root, "node_modules", "@phosphor-icons", "react", "dist", "csr");
const registryFile = path.join(root, "src", "lib", "icons", "phosphor-icon-registry.ts");
const loadersFile = path.join(root, "src", "components", "icons", "phosphor-icon-loaders.ts");
const groupsDir = path.join(root, "src", "components", "icons", "phosphor-icon-groups");
const check = process.argv.includes("--check");
if (!fs.existsSync(packageDir)) throw new Error(`Phosphor CSR directory not found: ${path.relative(root, packageDir)}`);
const iconNames = fs.readdirSync(packageDir).filter((file) => file.endsWith(".d.ts") && file !== "index.d.ts").map((file) => file.slice(0, -5)).filter((name) => fs.readFileSync(path.join(packageDir, `${name}.d.ts`), "utf8").includes(`${name}Icon`)).sort((a, b) => a < b ? -1 : a > b ? 1 : 0);
if (iconNames.length !== 1512) throw new Error(`Expected exactly 1512 canonical Phosphor icons, found ${iconNames.length}`);
const groupSize = 96;
const groups = [];
for (let index = 0; index < iconNames.length; index += groupSize) groups.push(iconNames.slice(index, index + groupSize));
const manifest = iconNames.map((name, index) => ({ name: `${name}Icon`, search: name.toLowerCase(), group: Math.floor(index / groupSize) }));
const registry = `// Generated by scripts/generate-phosphor-icon-registry.mjs. Do not edit manually.\nexport type PhosphorIconManifestEntry = { name: string; search: string; group: number };\n\nexport const PHOSPHOR_ICON_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly PhosphorIconManifestEntry[];\nexport const PHOSPHOR_ICON_NAMES = PHOSPHOR_ICON_MANIFEST.map((entry) => entry.name);\nconst phosphorNames = new Set<string>(PHOSPHOR_ICON_NAMES);\nexport function isPhosphorIconName(value: unknown): value is (typeof PHOSPHOR_ICON_MANIFEST)[number]["name"] { return typeof value === "string" && phosphorNames.has(value); }\nexport function getPhosphorIconManifestEntry(value: string) { return PHOSPHOR_ICON_MANIFEST.find((entry) => entry.name === value); }\n`;
const loaderEntries = groups.map((_, index) => `  ${index}: () => import("./phosphor-icon-groups/group-${String(index).padStart(3, "0")}"),`).join("\n");
const loaders = `// Generated by scripts/generate-phosphor-icon-registry.mjs. Do not edit manually.\nimport type { ComponentType } from "react";\nexport type PhosphorIconComponent = ComponentType<{ "aria-hidden"?: boolean | "true"; className?: string; size?: number; weight?: "thin" | "light" | "regular" | "bold" | "fill" | "duotone" }>;\nexport type PhosphorIconGroupModule = { ICONS: Record<string, PhosphorIconComponent> };\nexport const PHOSPHOR_ICON_GROUP_LOADERS: Record<number, () => Promise<PhosphorIconGroupModule>> = {\n${loaderEntries}\n};\n`;
const outputs = new Map([[registryFile, registry], [loadersFile, loaders]]);
groups.forEach((group, index) => {
  const imports = group.map((name) => `import { ${name}Icon } from "@phosphor-icons/react/dist/csr/${name}";`).join("\n");
  const entries = group.map((name) => `  ${name}Icon,`).join("\n");
  outputs.set(path.join(groupsDir, `group-${String(index).padStart(3, "0")}.ts`), `${imports}\n\nexport const ICONS = {\n${entries}\n} as const;\n`);
});
const expectedGroupFiles = new Set(groups.map((_, index) => `group-${String(index).padStart(3, "0")}.ts`));
const existingGroupFiles = fs.existsSync(groupsDir)
  ? new Set(fs.readdirSync(groupsDir).filter((file) => /^group-\d+\.ts$/.test(file)))
  : new Set();
const unexpectedGroupFiles = [...existingGroupFiles].filter((file) => !expectedGroupFiles.has(file));
if (unexpectedGroupFiles.length) throw new Error(`Unexpected generated group files: ${unexpectedGroupFiles.join(", ")}`);
let changed = false;
const targetDir = check ? fs.mkdtempSync(path.join(os.tmpdir(), "homeback-phosphor-registry-")) : null;
try {
  for (const [file, contents] of outputs) {
    const relative = path.relative(root, file);
    const generatedFile = targetDir ? path.join(targetDir, relative) : file;
    fs.mkdirSync(path.dirname(generatedFile), { recursive: true });
    fs.writeFileSync(generatedFile, contents);
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== contents) changed = true;
  }
} finally {
  if (targetDir) fs.rmSync(targetDir, { recursive: true, force: true });
}
if (check && changed) { console.error("Generated Phosphor registry is out of date. Run npm run icons:generate."); process.exitCode = 1; }
console.log(JSON.stringify({ icons: iconNames.length, groups: groups.length, groupSize, changed }, null, 2));
